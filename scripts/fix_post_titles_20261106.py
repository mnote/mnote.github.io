def weekday(d: str) -> str:
    y, m, dd = (int(x) for x in d.split("-"))
    return WEEK[date(y, m, dd).weekday()]


def title_for(d: str) -> str:
    s1, s2 = SUMMARY[d]
    assert len(s1) <= 10 and len(s2) <= 10, (d, s1, s2)
    return f"wu2198 投资日报 - {d}（{weekday(d)} {s1}，{s2}）"


def main():
    updated, added = [], []
    for f in sorted(POSTS.glob("*.html")):
        d = f.name[:10]
        if d not in SUMMARY:
            print(f"[skip] {f.name}: 日期 {d} 未收录摘要")
            continue
        text = f.read_text(encoding="utf-8")
        new_title = title_for(d)

        if text.startswith("---\n"):
            # 已有 front matter：只替换 title 一行
            end = text.index("\n---\n", 3)
            fm, body = text[4:end], text[end:]
            if re.search(r"^title:.*$", fm, re.M):
                fm = re.sub(r"^title:.*$", f"title: {new_title}", fm, flags=re.M)
            else:
                fm += f"\ntitle: {new_title}"
            f.write_text(f"---\n{fm}{body}", encoding="utf-8")
            updated.append(f.name)
        else:
            # 无 front matter：补一套（layout: null + 固定 permalink + title）
            permalink = f"/{f.stem}.html"
            fm = ("---\nlayout: null\n"
                  f"permalink: {permalink}\n"
                  f"title: {new_title}\n"
                  "tags: [weibo, wu2198, A股, 投资日报]\n---\n\n")
            f.write_text(fm + text, encoding="utf-8")
            added.append((f.name, permalink))

    print(f"[ok] 更新 title {len(updated)} 篇")
    for n in updated:
        print(f"     {n}")
    print(f"[ok] 补 front matter {len(added)} 篇")
    for n, p in added:
        print(f"     {n}  → permalink {p}")


if __name__ == "__main__":
    main()
